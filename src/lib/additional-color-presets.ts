import type { ThemeMode, ThemePalette } from "@/lib/site-theme";
type PaletteTones = Pick<
  ThemePalette,
  | "background"
  | "foreground"
  | "card"
  | "popover"
  | "primary"
  | "primaryForeground"
  | "secondary"
  | "muted"
  | "mutedForeground"
  | "accent"
  | "border"
  | "input"
>;
/** Complete palettes without inheriting unrelated colors from the initial forest theme. */
function completePalette(mode: ThemeMode, tones: PaletteTones): ThemePalette {
  return {
    ...tones,
    cardForeground: tones.foreground,
    popoverForeground: tones.foreground,
    secondaryForeground: tones.foreground,
    accentForeground: tones.foreground,
    destructive: mode === "light" ? "#b42332" : "#ff9b9b",
    ring: tones.primary,
  };
}
function preset(
  id: string,
  name: string,
  description: string,
  light: PaletteTones,
  dark: PaletteTones,
) {
  return {
    id,
    name,
    description,
    palettes: {
      light: completePalette("light", light),
      dark: completePalette("dark", dark),
    },
  };
}
